"""Direct, audited R10 preparation from genuine R01/R08 histogram exports.

This adapter constructs native source metadata without running R09. It preserves
inherited grouped query memberships and original query IDs. Raw coordinates
are parsed once into private caches; query truth is used only for offline audits.
"""
from __future__ import annotations

from datetime import datetime, timezone
import json
from pathlib import Path
import shutil
import time

import numpy as np
import pandas as pd

from . import local_shape as shape
from . import local_shape_workflow as workflow
from . import sidecar_workflow as prior
from .features import load_hist
from .sidecar_e2e import ScanCounter


def _config(config):
    supplied, inherited = dict(config), {}
    root = Path(supplied.get("run_dir") or ".").expanduser()
    if supplied.get("run_dir"):
        for name in ("run.json", "confirmation_config.json"):
            path = root/name
            if path.is_file():
                value = json.loads(path.read_text())
                inherited.update(value.get("config", value))
    inherited.pop("output_root", None)
    for key, value in supplied.items():
        if value != "" or key not in inherited:
            inherited[key] = value
    # Input preparation has no bounded-mixture compressor budget.
    if not inherited.get("budget_bytes"):
        inherited["budget_bytes"] = prior.DEFAULTS["budget_bytes"]
    return prior._config(inherited)


def _queries(cfg, query_path, split_path, destination):
    if split_path is None:
        raise ValueError("Direct preparation requires an explicit or inherited grouped cell split file")
    queries = prior._load_queries(query_path, cfg.get("query_metadata_file", ""))
    outer = pd.read_csv(split_path)
    if "seed" not in outer:
        if len(cfg["seeds"]) != 1:
            raise ValueError("A split file without seed requires one configured seed")
        outer["seed"] = cfg["seeds"][0]
    if "qId" not in outer or "split" not in outer:
        raise ValueError("Inherited split file requires qId and split")
    if "split_kind" in outer:
        kind = cfg.get("split_kind") or ("cell" if "cell" in set(outer.split_kind.astype(str)) else "")
        if kind != "cell":
            raise ValueError("Direct preparation requires inherited cell-group memberships")
        outer = outer[outer.split_kind.astype(str) == kind].copy()
    outer = outer[outer.seed.isin(cfg["seeds"])].copy()
    if "cell" not in outer:
        if "cell" not in queries:
            raise ValueError("Inherited split needs cell groups or query metadata providing cell")
        outer = outer.merge(queries[["qId", "cell"]], on="qId", validate="many_to_one")
    if outer.cell.isna().any() or outer.cell.astype(str).str.strip().eq("").any():
        raise ValueError("Inherited cell groups cannot be missing")
    outer["split_kind"] = "cell"
    selected = set(outer.qId)
    if selected-set(queries.qId):
        raise ValueError("Inherited splits refer to unknown query IDs")
    omitted = queries[~queries.qId.isin(selected)].copy()
    if (omitted.truth >= cfg["min_exact"]).any():
        raise ValueError("Inherited splits omit eligible queries meeting min_exact")
    omitted.assign(reason="not in inherited eligible cohort; no replacement").to_csv(
        destination/"queries_excluded_from_inherited_cohort.csv", index=False)
    retained = queries[queries.qId.isin(selected)].copy()
    outer.to_csv(destination/"outer_splits.csv", index=False)
    outer, _ = prior._splits(retained, {**cfg, "split_kind": "cell"}, destination/"outer_splits.csv")
    outer.to_csv(destination/"outer_splits.csv", index=False)
    retained[["qId", *workflow.GEOMETRY, "truth"]].to_csv(destination/"queries_offline.csv", index=False)
    return retained, len(queries), len(omitted)


def prepare_direct_inputs(config) -> Path:
    """Build a genuine ``preparation_dir`` directly from exports and raw files.

    Accepts explicit ``histogram_dir``, ``raw_data_dir``, ``queries_file`` and
    ``split_file``, or their inherited R08 ``run_dir`` configuration/paths.
    Existing cell-group train/calibration/test roles are mandatory. No roles,
    test labels, or replacement queries are generated by this function.
    """
    cfg = _config(config)
    if cfg.get("preparation_dir"):
        path, _ = workflow._load_preparation(cfg["preparation_dir"])
        return path
    destination = workflow._new(cfg["output_root"], "local-shape-direct-inputs")
    state = dict(status="preparing", study="local-shape-preparation", source_study="direct_arm_exports",
                 config=cfg, started_utc=datetime.now(timezone.utc).isoformat())
    workflow._write_state(destination, state)
    started = time.perf_counter()
    try:
        _, source_paths, base_path, raw_paths, query_path, split_path = prior._resolve_inputs(cfg)
        # Preserve known R08/R01 raw identities when their lineage supplies one.
        expected_raw = {}
        for root in {cfg.get("run_dir", ""), cfg.get("source15_dir", "")} - {""}:
            manifest_path = Path(root)/"raw_input_manifest.json"
            if manifest_path.is_file():
                for record in json.loads(manifest_path.read_text()):
                    if "source_id" in record and "raw_sha256" in record:
                        expected_raw[int(record["source_id"])] = record["raw_sha256"]
        for source, raw in zip(source_paths, raw_paths):
            expected = expected_raw.get(int(source.stem.split("_")[-1]))
            if expected is not None and prior._sha(raw) != expected:
                raise ValueError(f"Raw source SHA differs from inherited identity: {raw}")
        base = prior._validate_hist(load_hist(base_path))
        hists = [prior._validate_hist(load_hist(path), exact=True) for path in source_paths]
        total = sum(sum(map(int, hist[3].ravel())) for hist in hists)
        if not np.isclose(base[3].sum(), total, rtol=0, atol=1e-6):
            raise ValueError("Original H and exact source histogram masses differ")
        queries, all_queries, excluded = _queries(cfg, query_path, split_path, destination)
        native, cache, quad_dir = (destination/name for name in ("native", "raw_cache", "quadrants"))
        for folder in (native, cache, quad_dir):
            folder.mkdir()
        prior.save_histogram(destination/"original_H.hist", base)
        audit, manifest = [], []
        inputs = [base_path, *source_paths, query_path, split_path, *raw_paths]
        if cfg.get("query_metadata_file"):
            inputs.append(Path(cfg["query_metadata_file"]))
        for path in dict.fromkeys(inputs):
            manifest.append(dict(path=str(path.resolve()), bytes=path.stat().st_size, sha256=prior._sha(path)))
        identity = {item["path"]: item["sha256"] for item in manifest}
        for sid, (hist, source_path, raw) in enumerate(zip(hists, source_paths, raw_paths)):
            tick, before = time.perf_counter(), (raw.stat().st_size, raw.stat().st_mtime_ns)
            rows = sum(map(int, hist[3].ravel()))
            cache_path, quadrant_path = cache/f"source_{sid}.npy", quad_dir/f"source_{sid}.npy"
            points = np.lib.format.open_memmap(cache_path, mode="w+", dtype=np.float64, shape=(rows, 2))
            counts = np.zeros(hist[3].size, np.uint64)
            sums = np.zeros((hist[3].size, 5), float)
            quadrants = np.zeros((hist[3].size, 4), np.uint64)
            position, clipped = 0, 0
            for chunk in prior.iter_raw(raw, cfg["chunk_size"]):
                if position+len(chunk) > rows:
                    raise ValueError("Raw rows exceed source histogram mass")
                if ((chunk[:, 0] < base[1][0]) | (chunk[:, 0] > base[1][-1]) |
                        (chunk[:, 1] < base[2][0]) | (chunk[:, 1] > base[2][-1])).any():
                    raise ValueError("Raw source lies outside original H root")
                count, additive, rounding = prior._sufficient(chunk, hist)
                counts += count
                sums += additive
                clipped += rounding
                quadrants += shape.quadrant_counts_from_points(chunk, hist)
                points[position:position+len(chunk)] = chunk
                position += len(chunk)
            if position != rows or not np.array_equal(counts, hist[3].ravel()) or not np.array_equal(quadrants.sum(axis=1), counts):
                raise ValueError("Raw source counts do not reproduce exact exported cell masses")
            if before != (raw.stat().st_size, raw.stat().st_mtime_ns) or prior._sha(raw) != identity[str(raw.resolve())]:
                raise ValueError("Raw source identity changed during construction")
            points.flush()
            del points
            prior.save_histogram(native/f"src_{sid}.hist", hist)
            prior._save_structured_moments(native/f"src_{sid}-moments.bin", hist, prior._moments(counts, sums), sid)
            np.save(quadrant_path, quadrants, allow_pickle=False)
            audit.append(dict(source_id=sid, original_source_id=int(source_path.stem.split("_")[-1]),
                              raw_path=str(raw), raw_sha256=identity[str(raw.resolve())], raw_rows=rows,
                              source_cells=hist[3].size, quadrant_mass_matches=True,
                              arithmetic_clip_rows=clipped, raw_cache_bytes=cache_path.stat().st_size,
                              raw_cache_sha256=prior._sha(cache_path), quadrant_cache_bytes=quadrant_path.stat().st_size,
                              source_histogram_sha256=identity[str(source_path.resolve())],
                              construction_seconds=time.perf_counter()-tick))
        pd.DataFrame(audit).to_csv(destination/"source_audit.csv", index=False)
        prior._json(destination/"input_manifest.json", manifest)
        counter, parity = ScanCounter(workflow._raw_arrays(destination)), []
        indexed = queries.set_index("qId")
        for qid in prior._select(queries.qId, 8, 0, "direct-input-raw-parity"):
            row = indexed.loc[qid]
            value = counter.count(row[workflow.GEOMETRY].to_numpy(float))
            parity.append(dict(qId=qid, raw_count=value, stored_truth=int(row.truth), matches=value == int(row.truth)))
        pd.DataFrame(parity).to_csv(destination/"raw_truth_parity.csv", index=False)
        if not parity or not all(row["matches"] for row in parity):
            raise ValueError("Offline query truth failed deterministic closed-bound raw parity audits")
        if any(prior._sha(item["path"]) != item["sha256"] for item in manifest):
            raise ValueError("Source input identity changed during preparation")
        builder = destination/"builder_shape_inputs.py"
        shutil.copyfile(__file__, builder)
        artifacts = [destination/name for name in ("original_H.hist", "outer_splits.csv", "queries_offline.csv",
            "queries_excluded_from_inherited_cohort.csv", "source_audit.csv", "raw_truth_parity.csv", "input_manifest.json")]
        artifacts += [builder, *native.iterdir(), *quad_dir.iterdir()]
        state.update(status="prepared", source_r08_run=cfg.get("run_dir", ""), queries_file=str(query_path),
                     raw_rows=total, all_query_count=all_queries, inherited_eligible_query_count=len(queries),
                     excluded_query_count=excluded, native_bytes=sum(p.stat().st_size for p in native.iterdir()),
                     original_H_bytes=(destination/"original_H.hist").stat().st_size,
                     builder_code_sha256=prior._sha(builder), preparation_seconds=time.perf_counter()-started,
                     input_sha256={str(p.relative_to(destination)): prior._sha(p) for p in artifacts})
        workflow._write_state(destination, state)
        workflow._load_preparation(destination)
        return destination
    except BaseException as exc:
        workflow._fail(destination, state, exc)
        raise


def prepare_inputs(config) -> Path:
    """Use a completed R09 when available; otherwise prepare direct exports."""
    run = Path(dict(config).get("run_dir") or ".")/"run.json"
    if run.is_file():
        state = json.loads(run.read_text())
        if state.get("status") == "complete" and state.get("study") == "bounded-sidecar-e2e":
            return workflow.prepare_experiment(config)
    return prepare_direct_inputs(config)
